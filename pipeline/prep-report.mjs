#!/usr/bin/env node
// Writes a human-readable review sheet for prepared lectures, comparing the AI output with the original lecture.
//   node pipeline/prep-report.mjs --lectures lec:a,lec:b [--out reports/prep]
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadKb } from "./lib/kb.mjs";
import { buildPacket } from "./lib/prep-packet.mjs";
import { mentions } from "./lib/evidence.mjs";
import { nameKey } from "./lib/prep-assemble.mjs";
import { readJsonl, parseArgs } from "./lib/util.mjs";

const SITE = "https://sina-med.github.io/";
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ");

export function lectureReport(kb, lectureId) {
  const { records, relations } = loadKb(kb);
  const rows = records.map((r) => r.row), byId = new Map(rows.map((r) => [r.id, r]));
  const lec = byId.get(lectureId), slugId = lectureId.slice(4);
  const file = join(kb, "ai", lec.subject.slice(5), slugId + ".json");
  if (!existsSync(file)) throw new Error(`${lectureId} has not been prepared`);
  const doc = JSON.parse(readFileSync(file, "utf8")), R = doc.result;
  const imported = rows.filter((r) => r.origin !== "ai");
  const packet = buildPacket(lectureId, new Map(imported.map((r) => [r.id, r])), imported);
  const map = new Map(readJsonl(join(kb, "admin/concept-map.jsonl")).map((m) => [m.id, m.concept]));
  const cid = (key) => map.get(lectureId + "|" + key);
  const rels = relations.map((r) => r.row).filter((r) => r.origin === "ai" && (r.attrs.lectures || []).includes(lectureId));
  const queue = readJsonl(join(kb, "admin/review-queue.jsonl")).filter((q) => q.lecture === lectureId);
  const ref = (e) => { const tag = e.unit || e.ref || e.locator; const s = byId.get(tag); return s && s.type === "slide" ? `[slide ${s.body.n ?? s.body.label}](${SITE}${s.body.image})` : tag.startsWith("sec:") ? `section “${(byId.get(tag) || {}).title || tag}”` : tag; };
  const o = [];
  const P = doc.provenance, ev = doc.evidence, evTotal = Object.values(ev).reduce((a, b) => a + b, 0);

  o.push(`# ${lec.title}`, "", `\`${lectureId}\` · prepared with instructions ${doc.prompt_version} · worker: ${P.worker} · model: ${P.model}`, "",
    "> Everything on this page except the quotations was generated by AI and has **not** been medically verified.", "");
  o.push("## At a glance", "", "| | |", "|---|---|",
    `| Lecture material | ${imported.filter((r) => r.lecture === lectureId && r.type === "section").length} summary sections, ${(lec.body.exam_points || []).length} exam points, ${imported.filter((r) => r.lecture === lectureId && r.type === "slide" && r.body.text_origin !== "none").length} slides with text, ${imported.filter((r) => r.lecture === lectureId && r.type === "mcq").length} questions, ${imported.filter((r) => r.lecture === lectureId && r.type === "flashcard").length} flashcards |`,
    `| Concepts extracted | ${R.concepts.length} |`,
    `| Relationships suggested | ${R.relations.length} |`,
    `| Quotations checked | ${evTotal}: ${ev.exact} found word for word, ${ev.approximate} approximately, ${ev.weak} too short, ${ev.failed + ev["bad-ref"]} not found |`,
    `| Items dropped for structural errors | ${doc.dropped.length} |`,
    `| Audit findings | ${doc.audit ? doc.audit.findings.length + " problems, " + doc.audit.missed.length + " missed concepts" : "not audited"} |`,
    `| In the review queue | ${queue.length} |`,
    `| Time and resources | ${P.seconds ?? "?"} s, ${P.tokens ?? "?"} tokens (worker)${doc.audit ? `; ${doc.audit.seconds ?? "?"} s, ${doc.audit.tokens ?? "?"} tokens (audit)` : ""} |`, "");

  o.push("## AI summary", "", R.abstract, "", "**Keywords:** " + R.keywords.join(", "), "");

  // ---- coverage of the original lecture
  const names = R.concepts.map((c) => ({ c, names: [c.name, ...(c.aliases || [])] }));
  const found = (text) => names.filter((x) => x.names.some((n) => mentions(text, n) || mentions(text, nameKey(n)))).map((x) => x.c.name);
  const exam = (lec.body.exam_points || []).map((t, i) => ({ i: i + 1, t, hit: found(t) }));
  const cited = new Set(R.concepts.flatMap((c) => c.evidence.map((e) => e.ref)).concat(R.relations.flatMap((r) => r.evidence.map((e) => e.ref))));
  const secs = imported.filter((r) => r.lecture === lectureId && r.type === "section").sort((a, b) => a.body.order - b.body.order);
  const slides = imported.filter((r) => r.lecture === lectureId && r.type === "slide" && r.body.text_origin !== "none");
  const tagged = R.tests.filter((t) => t.concepts.length), untagged = R.tests.filter((t) => !t.concepts.length);
  const testedKeys = new Set(R.tests.flatMap((t) => t.concepts));
  o.push("## How much of the lecture is covered", "", "| Measure | Result |", "|---|---|",
    `| Exam points that mention at least one extracted concept | ${exam.filter((e) => e.hit.length).length} of ${exam.length} |`,
    `| Summary sections quoted as evidence | ${secs.filter((s) => cited.has(s.id)).length} of ${secs.length} |`,
    `| Slides quoted as evidence | ${slides.filter((s) => cited.has(s.id)).length} of ${slides.length} |`,
    `| Questions and flashcards linked to a concept | ${tagged.length} of ${packet.items.length} |`,
    `| Concepts tested by at least one question or flashcard | ${R.concepts.filter((c) => testedKeys.has(c.key)).length} of ${R.concepts.length} |`, "");
  const missExam = exam.filter((e) => !e.hit.length);
  if (missExam.length) o.push("Exam points with no extracted concept named in them:", "", ...missExam.map((e) => `- ${e.t}`), "");
  const missSec = secs.filter((s) => !cited.has(s.id));
  if (missSec.length) o.push("Sections never quoted: " + missSec.map((s) => `“${s.title}”`).join(", "), "");
  const missSlides = slides.filter((s) => !cited.has(s.id));
  if (missSlides.length) o.push("Slides never quoted: " + missSlides.map((s) => `[${s.body.n ?? s.body.label}](${SITE}${s.body.image})`).join(", "), "");
  if (untagged.length) o.push("Questions or flashcards with no concept: " + untagged.map((t) => "`" + t.item + "`").join(", "), "");
  const untested = R.concepts.filter((c) => !testedKeys.has(c.key));
  if (untested.length) o.push("Concepts no question tests: " + untested.map((c) => c.name).join(", "), "");

  // ---- concepts
  o.push("## Concepts", "", "Compare each definition with the lecture's own words in the last column.", "", "| Concept | Kind | Confidence → status | AI definition | Lecture's words (source) |", "|---|---|---|---|---|");
  for (const c of R.concepts) {
    const rec = byId.get(cid(c.key)), def = rec && rec.body.definitions.find((d) => d.lecture === lectureId);
    const status = def ? `${def.confidence} → ${def.status === "auto-accepted" ? "shown" : "held: " + (def.held_for || []).join(", ")}` : "?";
    const quotes = c.evidence.map((e) => `“${esc(e.quote)}” — ${ref(e)}${e.check === "exact" ? "" : ` ⚠ ${e.check}`}`).join("<br>");
    o.push(`| **${esc(c.name)}**${c.aliases && c.aliases.length ? "<br><sub>" + esc(c.aliases.join(", ")) + "</sub>" : ""} | ${c.kind} | ${status} | ${esc(c.definition)} | ${quotes} |`);
  }
  o.push("");

  // ---- relations
  const nameOf = (id) => (byId.get(id) || {}).title || id;
  o.push("## Relationships", "", "Read each as a sentence. The quotation is what the worker offered as support.", "", "| Relationship | Confidence → status | Lecture's words (source) |", "|---|---|---|");
  for (const r of rels.filter((x) => !["covers", "tests", "explains"].includes(x.type)).sort((a, b) => (a.type + nameOf(a.src) < b.type + nameOf(b.src) ? -1 : 1))) {
    const held = (r.attrs.held_for || []).join(", ");
    o.push(`| ${esc(nameOf(r.src))} **${r.type}** ${esc(nameOf(r.dst))}<br><sub>${esc(r.rationale || "")}</sub> | ${r.confidence} → ${r.status === "auto-accepted" ? "shown" : r.status === "proposed" ? "held: " + held : r.status} | ${(r.provenance || []).map((e) => `“${esc(e.quote)}” — ${ref(e)}`).join("<br>") || "—"} |`);
  }
  o.push("");

  // ---- tests
  o.push("## Which questions test which concepts", "", "| Question or flashcard | Concepts |", "|---|---|");
  for (const t of R.tests) { const x = byId.get(t.item); o.push(`| ${esc(x ? x.title : t.item)} <sub>\`${t.item}\`</sub> | ${t.concepts.map((k) => esc((R.concepts.find((c) => c.key === k) || {}).name)).join("; ") || "—"} |`); }
  o.push("");

  // ---- problems
  o.push("## Conflicts the worker reported in the lecture itself", "");
  if (!R.conflicts.length) o.push("None.", "");
  for (const c of R.conflicts) o.push(`- **${c.kind}**: ${c.issue}${(c.evidence || []).length ? " " + c.evidence.map((e) => `“${e.quote}” — ${ref(e)}`).join("; ") : ""}`);
  o.push("", "## Audit findings", "");
  if (!doc.audit) o.push("Not audited.", "");
  else {
    if (!doc.audit.findings.length) o.push("The auditor found no problems.", "");
    for (const f of doc.audit.findings) o.push(`- \`${f.target}\` — **${f.verdict}**: ${f.detail}`);
    if (doc.audit.missed.length) o.push("", "Concepts the auditor thinks were missed:", "", ...doc.audit.missed.map((m) => `- **${m.name}**: ${m.why}`));
    o.push("");
  }
  if (doc.dropped.length) o.push("## Dropped for structural errors", "", ...doc.dropped.map((d) => `- ${d}`), "");
  if ((R.notes || []).length) o.push("## Worker's notes", "", ...R.notes.map((n) => `- ${n}`), "");
  o.push("## Review queue entries for this lecture", "");
  if (!queue.length) o.push("None.", "");
  else { o.push("| Reason | Severity | What | Detail |", "|---|---|---|---|"); for (const q of queue) o.push(`| ${q.reason} | ${q.severity} | ${esc(q.summary)} | ${esc(q.detail || "")} |`); o.push(""); }
  return o.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const opts = parseArgs(process.argv.slice(2)), kb = opts.kb || "kb", out = opts.out || "reports/prep";
  mkdirSync(out, { recursive: true });
  for (const id of String(opts.lectures || "").split(",").filter(Boolean)) { const f = join(out, id.slice(4) + ".md"); writeFileSync(f, lectureReport(kb, id)); console.log("wrote " + f); }
}
